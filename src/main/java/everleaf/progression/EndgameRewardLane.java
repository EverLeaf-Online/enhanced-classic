package everleaf.progression;

/**
 * Independent progression lanes used by Everleaf's post-200 endgame.
 *
 * Keeping these explicit prevents future content from collapsing into a
 * single mandatory currency/activity path.
 */
public enum EndgameRewardLane {
    BOSS,
    WEEKLY,
    QUEST,
    PARTY,
    COLLECTION,
    GUILD
}
